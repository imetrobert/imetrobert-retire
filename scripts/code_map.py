#!/usr/bin/env python3
"""Writes docs/code-map.md: current line numbers of the main functions and anchors in
index.html, so nobody has to read the 400-600 KB file. Re-run after editing index.html
(the Checks workflow does it automatically)."""
import re, os, datetime
root = os.path.join(os.path.dirname(__file__), '..')
lines = open(os.path.join(root, 'index.html'), encoding='utf-8').read().split('\n')

anchors = [r'APP_VERSION\s*=', r'TFSA_ANNUAL_LIMIT\s*=', r'const MONEY_FIELDS', r'<style', r'<script>',
           r'data-step="[1-4]"', r'Object\.assign\(EXACT', r'P\.push\(\[', r'function getDefaultTaxRules']
funcs = re.compile(r'^\s*(?:async\s+)?function\s+([A-Za-z0-9_$]+)\s*\(')
out = ['# Code map (generated by scripts/code_map.py; do not edit by hand)', '',
       f'Generated {datetime.date.today()} from index.html ({len(lines)} lines). Open only the range you need:',
       '`Read` with offset and limit, or `grep -n name index.html`.', '', '## Anchors', '']
start = next((i for i, l in enumerate(lines) if '-->' in l), 0) + 1  # skip the AI MAP comment
seen = set()
for a in anchors:
    for n, l in enumerate(lines, 1):
        if n > start and re.search(a, l) and (a, l.strip()[:40]) not in seen:
            seen.add((a, l.strip()[:40]))
            out.append(f'- line {n}: `{l.strip()[:90]}`')
            if a.startswith('data-step') is False:
                break
out += ['', '## Functions (name: line)', '']
names = []
for n, l in enumerate(lines, 1):
    m = funcs.match(l) if n > start else None
    if m:
        names.append(f'{m.group(1)}:{n}')
out.append(' '.join(names))
os.makedirs(os.path.join(root, 'docs'), exist_ok=True)
open(os.path.join(root, 'docs', 'code-map.md'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print(f'wrote docs/code-map.md ({len(names)} functions)')
